"""Generate docs/data-sources.md and ATTRIBUTION.md from the dataset registry.

Run ``lix docs`` after editing config/datasets.yaml; CI can check the files are current.
"""

from collections import defaultdict
from urllib.parse import quote

from lix_core.config import NATION_NAMES, DatasetSpec, load_registry
from lix_core.paths import get_project_root

THEME_TITLES = {
    "geography": "Geography",
    "safety": "Safety",
    "environment": "Environment",
    "health": "Health access",
    "education": "Education & childcare",
    "transport": "Transport & connectivity",
    "amenities": "Amenities & nightlife",
    "housing": "Housing & affordability",
    "community": "Community & socio-economic",
    "climate": "Climate",
}

HEADER = "<!-- Generated by `lix docs` from config/datasets.yaml; do not edit by hand. -->\n\n"


def _cell(text: str | None) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def _link(spec: DatasetSpec) -> str:
    url = (
        spec.landing_page or getattr(spec.access, "url", None) or getattr(spec.access, "page", None)
    )
    if url is None and spec.access.type == "govuk_attachment":
        url = f"https://www.gov.uk/{spec.access.path}"
    if url is None and spec.access.type == "arcgis_item" and spec.access.query:
        # The ONS geoportal's search for the item's title
        url = "https://geoportal.statistics.gov.uk/search?q=" + quote(spec.access.query)
    if url is None and spec.access.type == "curated":
        url = f"../{spec.access.path}"  # the list lives in the repository
    return f"[{_cell(spec.title)}]({url})" if url else _cell(spec.title)


def data_sources_md(registry: dict[str, DatasetSpec]) -> str:
    by_theme: dict[str, list[tuple[str, DatasetSpec]]] = defaultdict(list)
    for slug, spec in registry.items():
        by_theme[spec.theme].append((slug, spec))

    from lix_pipeline.fetch.lock import read_lock
    from lix_pipeline.stage.periods import period_of

    lock = read_lock()
    lines = [
        HEADER + "# Data sources\n",
        f"{len(registry)} datasets, all under open licences. Each is pinned to a concrete file "
        'in `config/datasets.lock.json` by `lix resolve`. "Data for" is the period the data '
        'describes, as far as the publisher says; "Updated" is how often it is published.\n',
    ]
    for theme, title in THEME_TITLES.items():
        if theme not in by_theme:
            continue
        lines.append(f"\n## {title}\n")
        lines.append(
            "| Slug | Dataset | What it gives us | Covers | Data for | Updated | Licence |"
        )
        lines.append("|---|---|---|---|---|---|---|")
        for slug, spec in by_theme[theme]:
            licence = spec.licence + ("" if spec.licence_verified else " (unverified)")
            if spec.access.type == "api_key":
                where = f" from {spec.access.signup}" if spec.access.signup else ""
                licence += f"; free key{where} in `{spec.access.env}`"
            elif spec.access.type == "manual":
                licence += "; manual download (free login)"
            priority = "" if spec.priority == "P0" else f" ({spec.priority})"
            covers = ", ".join(NATION_NAMES[n] for n in spec.coverage)
            period = period_of(slug, spec, lock.get(slug, {}))
            lines.append(
                f"| `{slug}`{priority} | {_link(spec)} | {_cell(spec.description)} "
                f"| {covers} | {_cell(period['label'] if period else None)} | {spec.cadence} "
                f"| {licence} |"
            )
    return "\n".join(lines) + "\n"


def attribution_md(registry: dict[str, DatasetSpec]) -> str:
    seen: dict[str, list[str]] = {}
    for slug, spec in registry.items():
        seen.setdefault(spec.attribution.strip(), []).append(slug)
    lines = [
        HEADER + "# Attribution\n",
        "This project's outputs are built from the datasets below. Reuse must keep these "
        "notices. Data derived from OpenStreetMap is a derivative database under the Open "
        "Database Licence (ODbL) and must be shared under the same licence.\n",
    ]
    for text, slugs in seen.items():
        lines.append(f"- {text} ({', '.join(f'`{s}`' for s in slugs)})")
    return "\n".join(lines) + "\n"


def write_docs() -> list[str]:
    root = get_project_root()
    registry = load_registry()
    (root / "docs").mkdir(exist_ok=True)
    outputs = {
        root / "docs" / "data-sources.md": data_sources_md(registry),
        root / "ATTRIBUTION.md": attribution_md(registry),
    }
    for path, text in outputs.items():
        path.write_text(text)
    return [str(p.relative_to(root)) for p in outputs]
